"""
Shadow Guide Agent
====================
Patent Innovation #4: Stateful autonomous journey companion.

The Shadow Guide is a persistent agent that attaches to a user from the moment
they search for a journey until they arrive at their destination. It acts as
an intelligent travel companion that:

PRE-JOURNEY:
    - Monitors seat availability and alerts if status changes
    - Suggests optimal departure times based on crowd predictions
    - Pre-books station amenities (lounge, food) at wait stations
    - Sends weather alerts and packing suggestions

DURING JOURNEY:
    - Real-time delay monitoring with proactive alternatives
    - Emergency Intercept: Auto-finds bus/cab if train is stranded
    - Food ordering at upcoming stations
    - Safety monitoring (night travel, remote stops)
    - Platform change alerts

POST-JOURNEY:
    - Last-mile cab booking before arrival
    - Feedback collection with rewards
    - Loyalty point calculation and tier updates
    - Journey analytics for the user

Key Innovation:
    The "Emergency Intercept Protocol" - when a train delay exceeds a threshold,
    the agent autonomously finds the nearest alternative transport and presents
    it to the user BEFORE they need to ask.

Integration:
    - Extends: BaseAgent (agent swarm framework)
    - Uses: SupplyInfusionEngine (for alternatives), StationAmenityService (for food/lounge)
    - Reads: LiveStatusService, DelayPredictor, EmergencyServices
    - Events: EventBus for real-time notifications
"""

