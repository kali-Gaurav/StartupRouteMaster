    def _generate_journey_summary(self, journey: JourneyContext) -> Dict[str, Any]:
        """Generate a post-journey summary."""
        return {
            "journey_id": journey.journey_id,
            "route": f"{journey.source}->{journey.destination}",
            "total_alerts": len(journey.alerts),
            "delays_encountered": journey.last_known_delay_minutes > 0,
            "max_delay_minutes": journey.last_known_delay_minutes,
            "food_orders": len(journey.food_orders),
            "cab_bookings": len(journey.cab_bookings),
        }

    # =====================================================================
    # ACTION EXECUTOR
    # =====================================================================

    async def _execute_action(self, alert: GuideAlert, journey: JourneyContext):
        """Execute an automatic action from an alert."""
        action = alert.action_data

        if alert.action_type == "book" and action.get("type") == "lounge":
            try:
                from services.station_amenity_service import get_station_amenity_service
                amenity_svc = get_station_amenity_service()
                booking = await amenity_svc.book_waiting(
                    passenger_id=journey.user_id,
                    station_code=action["station"],
                    package_id="standard_wait",
                    start_time=datetime.utcnow(),
                )
                journey.lounge_bookings.append({"booking_id": booking.booking_id})
                logger.info(f"[ShadowGuide] Auto-booked lounge for journey {journey.journey_id}")
            except Exception as e:
                logger.warning(f"[ShadowGuide] Lounge booking failed: {e}")

        elif alert.action_type == "switch":
            logger.info(
                f"[ShadowGuide] Emergency switch suggested for {journey.journey_id}: "
                f"{action.get('mode')} via {action.get('provider')}"
            )

